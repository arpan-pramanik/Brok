#[tokio::main]
async fn main() -> anyhow::Result<()> {
    println!("{}", "=" .repeat(80));
    println!("   BRAGI RAG PIPELINE NATIVE RUST IMMENSE BENCHMARK (105 QUERIES)   ");
    println!("{}", "=" .repeat(80));

    let client = Client::builder()
        .timeout(Duration::from_secs(30))
        .build()?;

    let url = "http://localhost:8000/api/query";
    let mut results = Vec::new();
    let mut sub_150_count = 0;
    let start_suite = Instant::now();

    for (idx, &(category, query)) in QUERIES.iter().enumerate() {
        let payload = QueryPayload { query };
        let start = Instant::now();

        let resp_res = client.post(url).json(&payload).send().await;
        let latency_ms = start.elapsed().as_secs_f64() * 1000.0;

        if let Ok(resp) = resp_res {
            if resp.status().is_success() {
                let json_val: Value = resp.json().await.unwrap_or_default();
                let answer = json_val["answer"].as_str().unwrap_or("");
                let stages = json_val["stages"].as_array();

                let mut ret_ms = 0.0;
                let mut gen_ms = 0.0;

                if let Some(stg_arr) = stages {
                    for s in stg_arr {
                        let stg_name = s["stage"].as_str().unwrap_or("");
                        let dur = s["duration_ms"].as_f64().unwrap_or(0.0);
                        if stg_name == "retrieval" {
                            ret_ms = dur;
                        } else if stg_name == "generation" {
                            gen_ms = dur;
                        }
                    }
                }

                let is_abstained = answer.to_lowercase().contains("sorry i dont have");
                let status_str = if is_abstained { "ABSTAINED" } else { "ANSWERED" };
                let is_sub150 = latency_ms < 150.0;
                if is_sub150 {
                    sub_150_count += 1;
                }

                let query_trunc = if query.chars().count() > 40 {
                    format!("{}...", query.chars().take(40).collect::<String>())
                } else {
                    query.to_string()
                };

                let pass_icon = if is_sub150 { "✅ YES" } else { "❌ NO" };
                println!(
                    "[{:03}/{:03}][{:<13}] Query: \"{}\"",
                    idx + 1,
                    QUERIES.len(),
                    category,
                    query_trunc
                );
                println!(
                    "  Result: {:<9} | Latency: {:.2}ms [Ret: {:.1}ms, Gen: {:.1}ms] | Sub-150ms: {}",
                    status_str, latency_ms, ret_ms, gen_ms, pass_icon
                );

                results.push(TestResult {
                    id: idx + 1,
                    category,
                    query,
                    status: status_str.to_string(),
                    total_ms: latency_ms,
                    retrieval_ms: ret_ms,
                    gen_ms,
                    sub_150ms: is_sub150,
                });
            }
        }
    }

    let elapsed_suite = start_suite.elapsed().as_secs_f64();

    println!("\n{}", "=" .repeat(80));
    println!("              NATIVE RUST 105-QUERY BENCHMARK REPORT SUMMARY             ");
    println!("{}", "=" .repeat(80));

    if !results.is_empty() {
        let n = results.len();
        let mut totals: Vec<f64> = results.iter().map(|r| r.total_ms).collect();
        let mut retrievals: Vec<f64> = results.iter().map(|r| r.retrieval_ms).collect();
        let mut generations: Vec<f64> = results.iter().map(|r| r.gen_ms).collect();

        totals.sort_by(|a, b| a.partial_cmp(b).unwrap());
        retrievals.sort_by(|a, b| a.partial_cmp(b).unwrap());
        generations.sort_by(|a, b| a.partial_cmp(b).unwrap());

        let avg_tot: f64 = totals.iter().sum::<f64>() / n as f64;
        let avg_ret: f64 = retrievals.iter().sum::<f64>() / n as f64;
        let avg_gen: f64 = generations.iter().sum::<f64>() / n as f64;

        let p50 = totals[(n as f64 * 0.50) as usize];
        let p70 = totals[(n as f64 * 0.70) as usize];
        let p90 = totals[(n as f64 * 0.90) as usize];
        let p99 = totals[(n as f64 * 0.99) as usize];
        let p100 = totals[n - 1];

        let pass_rate = (sub_150_count as f64 / n as f64) * 100.0;

        println!("Total Test Cases   : {}", n);
        println!("Total Suite Time   : {:.2} seconds", elapsed_suite);
        println!("Pass Rate (<150ms) : {:.1}% ({}/{})", pass_rate, sub_150_count, n);
        println!("Average Latency    : {:.2} ms", avg_tot);
        println!("P50 Latency        : {:.2} ms", p50);
        println!("P70 Latency        : {:.2} ms", p70);
        println!("P90 Latency        : {:.2} ms", p90);
        println!("P99 Latency        : {:.2} ms", p99);
        println!("P100 Latency       : {:.2} ms", p100);
        println!("{}", "-" .repeat(80));
        println!("Average Retrieval  : {:.2} ms", avg_ret);
        println!("Average Generation : {:.2} ms", avg_gen);
        println!("{}", "=" .repeat(80));
    }

    Ok(())
}
