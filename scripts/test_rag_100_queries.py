def run_immense_benchmark():
    print("=" * 80)
    print(f"   BRAGI RAG PIPELINE IMMENSE 105-QUERY BENCHMARK (REALISTIC USE CASE)   ")
    print("=" * 80)
    print(f"Targeting Orchestrator at: {ORCHESTRATOR_URL}\n")

    results = []
    sub_150_count = 0
    total_queries = len(QUERIES)

    # Warmup query to ensure model VRAM allocation is active
    try:
        requests.post(ORCHESTRATOR_URL, json={"query": "warmup"}, timeout=10)
    except Exception:
        pass

    start_suite_time = time.time()

    for idx, (category, q) in enumerate(QUERIES, 1):
        payload = {"query": q}
        start_time = time.time()
        
        try:
            resp = requests.post(ORCHESTRATOR_URL, json=payload, timeout=30)
            latency_ms = (time.time() - start_time) * 1000.0
            
            if resp.status_code == 200:
                data = resp.json()
                answer = data.get("answer", "")
                stages = data.get("stages", [])
                
                retrieval_ms = 0.0
                guardrail_ms = 0.0
                gen_ms = 0.0
                
                for s in stages:
                    if s.get("stage") == "retrieval":
                        retrieval_ms = s.get("duration_ms", 0.0)
                    elif s.get("stage") == "guardrail":
                        guardrail_ms = s.get("duration_ms", 0.0)
                    elif s.get("stage") == "generation":
                        gen_ms = s.get("duration_ms", 0.0)
                        
                is_sub150 = latency_ms < 150.0
                if is_sub150:
                    sub_150_count += 1
                
                is_abstained = "sorry i dont have" in answer.lower()
                status_str = "ABSTAINED" if is_abstained else "ANSWERED"
                pass_icon = "✅ YES" if is_sub150 else "❌ NO"

                results.append({
                    "id": idx,
                    "category": category,
                    "query": q,
                    "status": status_str,
                    "latency_ms": latency_ms,
                    "retrieval_ms": retrieval_ms,
                    "guardrail_ms": guardrail_ms,
                    "gen_ms": gen_ms,
                    "sub_150": is_sub150
                })
                
                print(f"[{idx:03d}/{total_queries:03d}][{category:<13}] Query: \"{q[:45]}...\"")
                print(f"  Result: {status_str:<9} | Latency: {latency_ms:.2f}ms [Ret: {retrieval_ms:.1f}ms, Gen: {gen_ms:.1f}ms] | Sub-150ms: {pass_icon}")
            else:
                print(f"[{idx:03d}/{total_queries:03d}][{category:<13}] Query: \"{q[:45]}...\" ❌ HTTP {resp.status_code}")
        except Exception as e:
            print(f"[{idx:03d}/{total_queries:03d}][{category:<13}] Query: \"{q[:45]}...\" ❌ ERROR: {e}")

    total_suite_duration = time.time() - start_suite_time

    print("\n" + "=" * 80)
    print("                    105-QUERY BENCHMARK REPORT SUMMARY                   ")
    print("=" * 80)

    if results:
        latencies = [r["latency_ms"] for r in results]
        retrievals = [r["retrieval_ms"] for r in results]
        generations = [r["gen_ms"] for r in results]

        latencies.sort()
        retrievals.sort()
        generations.sort()

        n = len(latencies)
        p50 = latencies[int(n * 0.50)]
        p70 = latencies[int(n * 0.70)]
        p90 = latencies[int(n * 0.90)]
        p99 = latencies[int(n * 0.99)]
        p100 = latencies[-1]

        avg_lat = statistics.mean(latencies)
        pass_rate = (sub_150_count / n) * 100.0

        print(f"Total Test Cases   : {n}")
        print(f"Total Suite Time   : {total_suite_duration:.2f} seconds")
        print(f"Pass Rate (<150ms) : {pass_rate:.1f}% ({sub_150_count}/{n})")
        print(f"Average Latency    : {avg_lat:.2f} ms")
        print(f"P50 Latency        : {p50:.2f} ms")
        print(f"P70 Latency        : {p70:.2f} ms")
        print(f"P90 Latency        : {p90:.2f} ms")
        print(f"P99 Latency        : {p99:.2f} ms")
        print(f"P100 Latency       : {p100:.2f} ms")
        print("-" * 80)
        print(f"Average Retrieval  : {statistics.mean(retrievals):.2f} ms")
        print(f"Average Generation : {statistics.mean(generations):.2f} ms")
        print("=" * 80)
    else:
        print("No valid benchmark results recorded.")

if __name__ == "__main__":
    run_immense_benchmark()
